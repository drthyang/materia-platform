"""Generate the spgrep reference fixtures for MATERIA's irrep engine.

Writes src/core/crystal/irreps/fixtures/spgrep-small-representations.json:
for each (space group, k) the little group's operations and the characters of
every small representation spgrep computes on them, with its Frobenius-Schur
indicator. MATERIA compares characters, never matrices (ADR 0003, 0005).

spgrep is BSD-3-Clause (Shinohara, Togo & Tanaka, JOSS 8 (2023) 5269,
https://github.com/spglib/spgrep); spglib is BSD-3-Clause. Neither is vendored:
the fixtures are their output, committed with this attribution.

Run in a scratch venv (never committed):
    uv venv && uv pip install spgrep spglib numpy
    .venv/bin/python -I scripts/subgroup-engine/spgrep_fixtures.py OUT.json
"""

from __future__ import annotations

import json
import sys
from fractions import Fraction

import numpy as np
import spglib
import spgrep
from spgrep import get_spacegroup_irreps
from spgrep.rep.irreps import frobenius_schur_indicator

# (name, Hall number, lattice (rows), k in the conventional reciprocal basis)
CUBIC = np.eye(3) * 5.0
CASES = [
    ("Pm-3m Γ", 517, CUBIC, [0, 0, 0]),
    ("Fm-3m Γ", 523, CUBIC, [0, 0, 0]),
    ("Fm-3m X", 523, CUBIC, [0, 0, 1]),
    ("F-43m X", 512, CUBIC, [0, 0, 1]),
    ("Fd-3m:2 Γ", 526, CUBIC, [0, 0, 0]),
    ("Fd-3m:2 X", 526, CUBIC, [0, 0, 1]),
    ("Im-3m H", 529, CUBIC, [0, 0, 1]),
    ("I4/mmm (0,0,1)", 424, np.diag([4.0, 4.0, 7.0]), [0, 0, 1]),
    ("R-3m:H (0,0,1)", 458, np.array([[4.0, 0, 0], [-2.0, 2.0 * np.sqrt(3), 0], [0, 0, 10.0]]), [0, 0, 1]),
    ("Cmcm (0,1,0)", 298, np.diag([4.0, 5.0, 6.0]), [0, 1, 0]),
    ("Pnma Γ", 292, np.diag([4.0, 5.0, 6.0]), [0, 0, 0]),
    ("P4 Γ", 349, np.diag([4.0, 4.0, 6.0]), [0, 0, 0]),
]

# Two generic orbits of different species, so the structure has no symmetry beyond the group's.
GENERIC = [np.array([0.1234, 0.2345, 0.3456]), np.array([0.4321, 0.0765, 0.1987])]


def frac(x: float) -> str:
    f = Fraction(x).limit_denominator(48)
    assert abs(float(f) - x) < 1e-8, x
    return f"{f.numerator}/{f.denominator}" if f.denominator != 1 else str(f.numerator)


def structure(hall: int, lattice: np.ndarray):
    sym = spglib.get_symmetry_from_database(hall)
    positions, numbers = [], []
    for species, x in enumerate(GENERIC, start=1):
        orbit = []
        for r, t in zip(sym["rotations"], sym["translations"]):
            p = (r @ x + t) % 1.0
            if not any(np.allclose((p - q + 0.5) % 1.0 - 0.5, 0, atol=1e-6) for q in orbit):
                orbit.append(p)
        positions += orbit
        numbers += [species] * len(orbit)
    return lattice, np.array(positions), numbers


def case(name: str, hall: int, lattice: np.ndarray, k: list[int]) -> dict:
    cell = structure(hall, lattice)
    dataset = spglib.get_symmetry_dataset(cell)
    expected = spglib.get_spacegroup_type(hall)
    assert dataset.number == expected.number, (name, dataset.number)
    irreps, rotations, translations, mapping = get_spacegroup_irreps(*cell, kpoint=np.array(k, dtype=float))
    ops = [
        {"rotation": rotations[i].tolist(), "translation": [frac(((x % 1.0) + 1.0) % 1.0) for x in translations[i]]}
        for i in mapping
    ]
    out = []
    for irrep in irreps:
        chars = np.trace(irrep, axis1=1, axis2=2)
        out.append({
            "dim": int(irrep.shape[1]),
            "indicator": int(frobenius_schur_indicator(irrep)),
            "characters": [[round(float(c.real), 6) + 0.0, round(float(c.imag), 6) + 0.0] for c in chars],
        })
    return {"name": name, "hall": hall, "spaceGroup": expected.number, "k": k, "littleGroup": ops, "irreps": out}


def main() -> None:
    out_path = sys.argv[1]
    data = {
        "source": (
            f"Generated by scripts/subgroup-engine/spgrep_fixtures.py with spgrep {spgrep.__version__} "
            f"and spglib {spglib.__version__} (both BSD-3-Clause; spgrep: Shinohara, Togo & Tanaka, "
            "JOSS 8 (2023) 5269, https://github.com/spglib/spgrep). Small representations of the "
            "little group at k (conventional cell and reciprocal basis), translations acting as "
            "exp(-2 pi i k.t): spgrep's convention, the complex conjugate of MATERIA's (ISODISTORT's)."
        ),
        "license": "BSD-3-Clause (spgrep, spglib); fixture data are their output",
        "cases": [case(*c) for c in CASES],
    }
    # One case per line keeps the file small and its diffs readable.
    cases = data.pop("cases")
    with open(out_path, "w") as f:
        head = json.dumps(data, ensure_ascii=False)[:-1]
        f.write(head + ',\n "cases": [\n')
        f.write(",\n".join(json.dumps(c, ensure_ascii=False, separators=(",", ":")) for c in cases))
        f.write("\n]}\n")


if __name__ == "__main__":
    main()
