/**
 * A fixed solvable chain of a crystallographic point group, for chain
 * induction (projective.ts): generators r₁, r₂, … such that, with H₀ = {E}
 * and Hᵢ = ⟨Hᵢ₋₁, rᵢ⟩, every Hᵢ₋₁ is normal in Hᵢ, rᵢ has order
 * pᵢ = [Hᵢ : Hᵢ₋₁], and the powers of rᵢ meet Hᵢ₋₁ only in E. Every step has
 * index 2 or 3, except the cyclic groups 4 and -4, which are built in one step
 * of order 4 (as spgrep does: 4 cannot be split over its subgroup 2).
 *
 * The chain is chosen deterministically from the matrices alone, so the
 * representation bases built on it, and the order-parameter directions read
 * in them, do not depend on the order of the operation list:
 *
 *  - a centrosymmetric group: its rotation subgroup, then −1;
 *  - any other group with improper elements: the chain of its proper
 *    isomorph R ↦ det(R)·R, mapped back (mm2 follows 222, -43m follows 432);
 *  - a cyclic group 2, 3 or 4: its generator; 6: the 3, then the 2;
 *  - a dihedral group 222, 32, 422, 622: its principal cyclic subgroup (for
 *    222 the axis along c when it has one), then a 2-fold;
 *  - 23: its 222, then a 3-fold; 432: its 23, then a 2-fold.
 *
 * Where a choice remains (which generator, which 2-fold), the first matrix in
 * a fixed lexicographic order is taken.
 */

import { idet, ikey, imul, iIsIdentity, iIsMinusIdentity, type IMat } from "@/core/crystal/irreps/rational";

const neg = (W: IMat): IMat => W.map((r) => r.map((x) => -x)) as unknown as IMat;

function orderOf(W: IMat): number {
  let P = W;
  for (let n = 1; n <= 6; n++) {
    if (iIsIdentity(P)) return n;
    P = imul(P, W);
  }
  throw new Error(`chain: ${ikey(W)} has no crystallographic order`);
}

/** The subgroup a set of matrices generates. */
function generated(gens: readonly IMat[]): IMat[] {
  const out = new Map<string, IMat>([[ikey([[1, 0, 0], [0, 1, 0], [0, 0, 1]]), [[1, 0, 0], [0, 1, 0], [0, 0, 1]]]]);
  const queue = [...out.values()];
  while (queue.length > 0) {
    const a = queue.pop()!;
    for (const g of gens) {
      const b = imul(a, g);
      const k = ikey(b);
      if (!out.has(k)) {
        out.set(k, b);
        queue.push(b);
      }
    }
  }
  return [...out.values()];
}

/** A fixed order of matrices: lexicographic on the entries, largest first. */
const canonical = (list: readonly IMat[]): IMat[] => [...list].sort((a, b) => (ikey(a) < ikey(b) ? 1 : ikey(a) > ikey(b) ? -1 : 0));

/** Whether a proper rotation is about c (it fixes (0,0,1)). */
function isAlongC(W: IMat): boolean {
  // A proper rotation about c fixes (0,0,1).
  return W[0][2] === 0 && W[1][2] === 0 && W[2][2] === 1;
}

/** The chain generators of a proper rotation group, bottom first. */
function properChain(group: readonly IMat[]): IMat[] {
  const n = group.length;
  if (n === 1) return [];
  const byOrder = (o: number): IMat[] => canonical(group.filter((W) => orderOf(W) === o));
  const cyclicGen = byOrder(n)[0];
  if (cyclicGen) {
    if (n === 6) {
      // 6 = 3 ⋊ 2: the 3-fold subgroup ⟨g²⟩, then g³.
      const g2 = imul(cyclicGen, cyclicGen);
      return [...properChain(generated([g2])), imul(g2, cyclicGen)];
    }
    return [cyclicGen];
  }
  const twos = byOrder(2);
  const threes = byOrder(3);
  if (n === 12 && threes.length === 8) {
    // 23: its 222 (the three 2-folds), then a 3-fold.
    return [...properChain(generated(twos)), threes[0]!];
  }
  if (n === 24) {
    // 432: its 23 (generated by the 3-folds), then a 2-fold outside it.
    const t = generated(threes);
    const tk = new Set(t.map(ikey));
    const r = twos.find((W) => !tk.has(ikey(W)))!;
    return [...properChain(t), r];
  }
  // Dihedral 222, 32, 422, 622: the principal cyclic subgroup, then a 2-fold outside it.
  const principalOrder = n / 2;
  const principal = principalOrder === 2 ? (twos.find(isAlongC) ?? twos[0]!) : byOrder(principalOrder)[0]!;
  const cyc = generated([principal]);
  const ck = new Set(cyc.map(ikey));
  const r = twos.find((W) => !ck.has(ikey(W)));
  if (!r || cyc.length !== principalOrder) throw new Error(`chain: no dihedral decomposition of a group of order ${n}`);
  return [...properChain(cyc), r];
}

/**
 * The chain generators (bottom first) of a point group, as indices into
 * `elements` (the group's matrices, in any order).
 */
export function pointGroupChain(elements: readonly IMat[]): number[] {
  const index = new Map(elements.map((W, i) => [ikey(W), i] as const));
  const at = (W: IMat): number => {
    const i = index.get(ikey(W));
    if (i === undefined) throw new Error(`chain: ${ikey(W)} is not in the group`);
    return i;
  };
  const inversion = elements.find(iIsMinusIdentity);
  if (inversion) {
    const proper = elements.filter((W) => idet(W) > 0);
    return [...properChain(proper).map(at), at(inversion)];
  }
  if (elements.some((W) => idet(W) < 0)) {
    // The proper isomorph φ(R) = det(R)·R; its chain mapped back by φ⁻¹.
    const phi = (W: IMat): IMat => (idet(W) < 0 ? neg(W) : W);
    const back = new Map(elements.map((W) => [ikey(phi(W)), W] as const));
    return properChain(elements.map(phi)).map((P) => at(back.get(ikey(P))!));
  }
  return properChain(elements).map(at);
}
