/**
 * Every subgroup of the parent that keeps its conventional cell — the
 * subgroups of the factor group F = G/ℤ³ (factorGroup.ts): t-subgroups (all
 * centring translations kept), decentring k-subgroups (the point group kept,
 * some centring lost: F/I/C/A/B/R → P, F → C, …) and the general subgroups
 * that lose both. Phase 1's subgroup lattice; supercells come in Phase 2.
 *
 * Enumeration after Hatch & Stokes, Phys. Rev. B 31 (1985) 2908, §III: a
 * subgroup H is fixed by its point group H̄ ≤ Ḡ, its translations T_H (here a
 * subgroup of the centring group C = Λ/ℤ³ that H̄ leaves invariant) and the
 * translations of its generators, which matter only modulo T_H. For each
 * (H̄, T_H) the candidates are the |C/T_H|^{#generators} lifts of a generating
 * set of H̄; a candidate is a subgroup when the group it generates has
 * exactly |H̄|·|T_H| elements (no translations beyond T_H). The search is
 * finite and exhaustive.
 */

import type { SymmetryOperation } from "@/core/crystal/types";
import { allSubgroups, buildCosetContext } from "@/core/magnetic/subgroupLattice";
import type { FactorGroup } from "@/core/crystal/irreps/factorGroup";
import { indexSplit, type IndexSplit } from "@/core/crystal/irreps/isotropy";
import { ikey, iIsIdentity } from "@/core/crystal/irreps/rational";

export type SubgroupKind = "parent" | "t" | "k" | "general";

export interface SameCellSubgroup {
  /** Its factor-group elements, ascending. */
  readonly elements: readonly number[];
  /** Its operations in the parent's cell, the centring translations it keeps included. */
  readonly operations: readonly SymmetryOperation[];
  readonly index: IndexSplit;
  /** t: all translations kept; k: the point group kept; general: neither. */
  readonly kind: SubgroupKind;
  /** 0-based conjugacy class (contiguous in the output). */
  readonly classId: number;
  readonly classRepresentative: boolean;
  /** Conjugate subgroups in the class, [G : N_G(H)]. */
  readonly conjugates: number;
  /** Domain states, [G : H]. */
  readonly domainStates: number;
}

/** The group generated by a set of elements (indices), by closure under right multiplication. */
function generate(group: FactorGroup, gens: readonly number[]): number[] {
  const inSet = new Set<number>([group.identity]);
  const queue = [group.identity];
  while (queue.length > 0) {
    const a = queue.pop()!;
    for (const g of gens) {
      const b = group.table[a]![g]!;
      if (!inSet.has(b)) {
        inSet.add(b);
        queue.push(b);
      }
    }
  }
  return [...inSet].sort((x, y) => x - y);
}

/**
 * Every subgroup of F up to `maxIndex` (all of them by default), grouped into
 * conjugacy classes, index ascending (the parent first), conjugates contiguous.
 */
export function sameCellSubgroups(group: FactorGroup, opts: { readonly maxIndex?: number } = {}): SameCellSubgroup[] {
  const F = group.elements.length;
  const maxIndex = opts.maxIndex ?? Number.POSITIVE_INFINITY;
  const centring = group.elements.map((e, i) => (iIsIdentity(e.W) ? i : -1)).filter((i) => i >= 0);
  // Elements by rotation.
  const byRotation = new Map<string, number[]>();
  group.elements.forEach((e, i) => {
    const key = ikey(e.W);
    const list = byRotation.get(key);
    if (list) list.push(i);
    else byRotation.set(key, [i]);
  });
  // Subgroups of the centring group (it is abelian and small).
  const centringSubgroups: number[][] = [];
  for (let mask = 0; mask < 1 << centring.length; mask++) {
    const gens = centring.filter((_, b) => mask & (1 << b));
    const T = generate(group, gens);
    if (!centringSubgroups.some((s) => s.length === T.length && s.every((x, i) => x === T[i]))) centringSubgroups.push(T);
  }
  // Point subgroups, as sets of rotation keys.
  const ctx = buildCosetContext(group.operations);
  const wKey = (op: SymmetryOperation): string => op.rotation.map((row) => row.map((x) => Math.round(x)).join(",")).join(";");
  const pointSubgroups = allSubgroups(ctx).map((S) => S.map((ci) => wKey(ctx.cosets[ci]!)));

  const found = new Map<string, number[]>();
  for (const rotations of pointSubgroups) {
    if (F / (rotations.length * centring.length) > maxIndex) continue;
    // A generating set of the rotation group, greedily.
    const repOf = (r: string): number => byRotation.get(r)![0]!;
    const gens: string[] = [];
    let span = new Set<string>([ikey(group.elements[group.identity]!.W)]);
    for (const r of rotations) {
      if (span.has(r)) continue;
      gens.push(r);
      span = new Set(generate(group, gens.map(repOf)).map((i) => ikey(group.elements[i]!.W)));
    }
    for (const T of centringSubgroups) {
      const order = rotations.length * T.length;
      if (F / order > maxIndex) continue;
      // T must be invariant under the rotations.
      const tSet = new Set(T);
      const invariant = gens.every((r) => {
        const g = repOf(r);
        return T.every((t) => tSet.has(group.table[group.table[g]![t]!]![group.inverse[g]!]!));
      });
      if (!invariant) continue;
      // Lifts of each generator modulo T.
      const choices = gens.map((r) => {
        const all = byRotation.get(r)!;
        const reps: number[] = [];
        const covered = new Set<number>();
        for (const f of all) {
          if (covered.has(f)) continue;
          reps.push(f);
          for (const t of T) covered.add(group.table[f]![t]!);
        }
        return reps;
      });
      const pick: number[] = gens.map(() => 0);
      for (;;) {
        const H = generate(group, [...T, ...pick.map((p, i) => choices[i]![p]!)]);
        if (H.length === order) {
          const key = H.join(",");
          if (!found.has(key)) found.set(key, H);
        }
        let i = 0;
        while (i < pick.length && ++pick[i]! >= choices[i]!.length) pick[i++] = 0;
        if (i === pick.length) break;
      }
    }
  }

  // Conjugacy classes under F.
  const subgroups = [...found.values()].sort((a, b) => b.length - a.length || (a.join(",") < b.join(",") ? -1 : 1));
  const classOf = new Map<string, number>();
  const classSize: number[] = [];
  for (const H of subgroups) {
    const key = H.join(",");
    if (classOf.has(key)) continue;
    const id = classSize.length;
    const members = new Set<string>();
    for (let g = 0; g < F; g++) members.add(H.map((h) => group.table[group.table[g]![h]!]![group.inverse[g]!]!).sort((x, y) => x - y).join(","));
    for (const m of members) classOf.set(m, id);
    classSize.push(members.size);
  }
  const seen = new Set<number>();
  const out = subgroups.map((H) => {
    const classId = classOf.get(H.join(","))!;
    const representative = !seen.has(classId);
    seen.add(classId);
    const index = indexSplit(group, H);
    const kind: SubgroupKind = H.length === F ? "parent" : index.k === 1 ? "t" : index.t === 1 ? "k" : "general";
    return {
      elements: H,
      operations: H.map((i) => group.operations[i]!),
      index,
      kind,
      classId,
      classRepresentative: representative,
      conjugates: classSize[classId]!,
      domainStates: F / H.length,
    } satisfies SameCellSubgroup;
  });
  return out.sort((a, b) => a.domainStates - b.domainStates || a.classId - b.classId);
}
